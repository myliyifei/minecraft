/**
 * 单次鼠标增量的隐含指针速度上限（像素/毫秒）。
 *
 * 超过它就当浏览器吐的假增量。这个数不是手调出来的：见 `isPointerSpike` 的注释里
 * 记的那次实测——真实增量最快 30 px/ms，假增量最慢 963 px/ms，阈值落在中间。
 */
const MAX_POINTER_SPEED = 300;

/**
 * 幅度低于这个像素数的增量一律采用。
 *
 * 时间戳的分辨率有限，小增量算出来的速度噪声很大；而假增量的幅度比它大一个数量级，
 * 所以先用幅度把小增量整批放行，速度判据只用来看那些本来就异常大的。
 */
const MIN_SUSPECT_PX = 60;

/**
 * 这一发鼠标增量是不是浏览器吐出来的假增量。
 *
 * 为什么需要它：WSL2 + Chrome 的指针锁定下实测到，连续转动的过程中浏览器会周期性地
 * 投递一发幅度几乎恒定的巨型 `movementX`——三秒的采样里 18 次，每次 562–578px，而
 * 同期真实增量的中位数只有 2px。幅度与手速无关，所以它不携带任何手的位移信息。
 * 照单全收的话，光这 18 发就让视角多转了 1284°（3.6 圈），画面于是「一瞬间跳到另一个
 * 方向」。指针锁定本身是正常的：那段采样里 `screenX`/`clientX` 全程只取一个值，
 * 光标没有在动，所以不是光标被搬来搬去造成的。
 *
 * 判据用隐含的指针速度而不是幅度：幅度大小和 DPI、灵敏度都相关，速度不相关。
 * 实测那一段里真实增量最快 30 px/ms（16px / 0.6ms），假增量 963–2830 px/ms
 * （578px / 0.6ms ～ 566px / 0.2ms），中间差 32 倍。
 *
 * 时间戳没前进也算假的：同一时刻的位移上一发已经报过了。
 *
 * 代价说清楚：DPI 极高（两万以上）配极低灵敏度的鼠标，一次猛甩有可能真的超过
 * 300 px/ms 而被误剔，代价是那一发的位移丢掉（约一毫秒的手位移）。真出现的话
 * 该调的是这里的阈值，而不是把整个判据去掉。
 */
export function isPointerSpike(movementPx: number, elapsedMs: number): boolean {
  if (movementPx <= MIN_SUSPECT_PX) return false;
  if (!(elapsedMs > 0)) return true;
  return movementPx / elapsedMs > MAX_POINTER_SPEED;
}
